"""여러 프롬프트가 공유하는 "스탯 판단 규칙" 조각 모음.

스탯창 피드백 프롬프트 두 개(chat/vision/scoreboard.py)와 채팅 답변의
stat_analysis_instruction(chat/graph/nodes_answer.py)이 같은 기준을 써야 하므로
여기서만 관리하고 세 프롬프트가 조립해 쓴다. 판단 기준을 바꿀 때는 이 파일만
고치면 된다.

모든 상수는 "- "로 시작하는 완성된 불릿 한 덩어리다(이어지는 줄은 공백 2칸
들여쓰기).
"""

# 스탯을 그 영웅의 킷 관점에서 먼저 해석하라는 규칙. 없으면 애초에 불가능한
# 지적(힐 전담 영웅에게 딜 요구 등)이 나간다.
HERO_KIT_AWARENESS_RULE = """- 스탯 항목마다 그 영웅이 애초에 그 수치를 낼 수 있는 스킬을 가졌는지부터
  너의 오버워치2 지식으로 판단해라. 힐 전담형 영웅의 낮은 피해량, 피해를
  막거나 흡수하는 스킬(방벽·보호막·벽 등)이 없는 영웅의 경감량 0은 전부
  구조적으로 정상인 수치이니 약점으로 지적하지 마라. 특히 경감량은 실제로
  그런 스킬을 쓴 결과로만 기록되는 값이므로, 그런 스킬이 없는 영웅에게
  "경감량이 낮으니 어떤 스킬을 더 활용했어야 한다"처럼 확인되지 않은
  스킬 운용을 지어내지 마라. 반대로 수치가 높다고 "OO 스킬을 효율적으로
  활용했다"처럼 실제로 확인할 수 없는 특정 스킬 사용을 칭찬하지도 마라
  (예: 피해량이 높다고 특정 기동 스킬을 잘 썼다고 단정하지 마라).
  킬/데스/딜량/힐량/경감량처럼 스탯으로 실제 확인된 수치 자체만 근거로 삼아라."""

# 메르시 예외. 추상적 표현("힐 전담형")만으로는 아래 비교 규칙에 밀리므로
# 구체 사례로 못박는다. 치유량은 예외가 아니라는 단서가 함께 가야 한다.
MERCY_DAMAGE_EXCLUSION_NOTE = """메르시처럼 피해 증폭(우클릭) 말고는 사실상
  자체 공격 수단이 없는 힐러는, 상대 힐러가 딜을 얼마나 냈든 상관없이 피해량
  항목 자체를 비교·지적 대상에서 제외해라 — "상대 힐러는 공격적으로
  운영했는데 이쪽은 피해 기여가 없다" 같은 문장도 이런 힐러에게는 쓰지 마라.
  단, 치유량은 예외가 아니다 — 이런 힐러도 치유량이 같은 역할 상대보다
  유의미하게 낮으면 그건 정상적인 약점 지적 대상이다."""

# 팀 내부 숫자만으로 판단하지 말고 상대팀 같은 역할과 비교하라는 규칙.
PEER_COMPARISON_RULE = f"""- 치유량 대비 피해량 비율처럼 팀 내부 숫자만 보고 판단하지 말고, 상대팀에서
  같은 역할 영웅의 실제 수치와 비교해서 상대적으로 높은지 낮은지를 근거로
  삼아라. 상대 같은 역할보다 치유량과 피해량이 모두 앞선다면 그건 약점이
  아니라 강점이니 아쉬운 점으로 지적하지 마라. 단, 이 비교 규칙은 두 힐러
  모두 스스로 의미 있는 피해를 낼 수 있는 킷일 때만 적용해라. {MERCY_DAMAGE_EXCLUSION_NOTE}"""

# 경감량은 킷에 따라 구조적으로 몇 배씩 차이가 난다.
MITIGATION_KIT_RULE = """- 경감량도 같은 원리로 판단해라: 방벽·보호막이나 디플렉트/매트릭스처럼
  피해를 흡수·차단하는 스킬이 있는 탱커(예: 라인하르트, 시그마, 디바)는
  그런 스킬이 없는 탱커보다 경감량이 구조적으로 훨씬 높게 나온다. 비교
  대상 탱커끼리 킷이 다르면 경감량 차이만으로 어느 쪽이 못했다고 판단하지
  마라 — 그 탱커에게 없는 스킬을 기준으로 "경감이 부족하다"고 지적하지 마라."""

# 자원을 소모해 채우는 킷(모이라 등)은 총합보다 배분이 중요하다.
RESOURCE_HEALER_RULE = """- 회복 자원을 소모해 채워야 하는 킷(자원이 바닥나면 다시 찰 때까지 치유를
  못 하는 힐러 등)을 쓰는 영웅은, 치유량/피해량 총합 수치만 보지 말고 두
  수치를 어떻게 배분했는지도 함께 판단해라. 치유와 피해(또는 견제)를 그
  영웅의 자원 관리 메커니즘에 맞게 오가며 운용했다면 총합 수치가 낮아도 잘한
  플레이로 봐야 하고, 자원 관리 없이 한쪽에만 치우쳤다면 총합이 높아도 운용이
  미숙했을 수 있다는 걸 감안해 판단해라."""

# "생존력이 뛰어난 영웅임에도 0데스"처럼 원인과 결과가 뒤집힌 문장을 막는다.
HERO_TRAIT_PHRASING_RULE = """- 영웅의 고유 특성(예: 생존력이 높다, 기동성이 좋다)을 근거로 언급할 때,
  그 특성 덕분에 나온 결과(예: 데스가 적음)를 "~인 영웅임에도" 처럼
  특성과 결과가 서로 모순되는 것처럼 쓰지 마라. 특성이 원인이라면
  "~답게", "~덕분에"처럼 인과관계가 맞는 표현만 써라(예: "생존력이 뛰어난
  영웅답게 0데스를 유지하며..." O, "생존력이 뛰어난 영웅임에도 0데스" X)."""

# 메르시가 아닌 힐러의 딜량을 순위/비교에서 빼지 말라는 규칙(채팅 답변 전용 —
# 스탯창 카드는 개인 순위를 매기지 않으므로 필요 없다).
SUPPORT_DAMAGE_CONTRIBUTION_RULE = """- 메르시가 아닌 힐러(모이라, 바티스트, 젠야타, 아나, 라이프위버 등)는
  힐량과 별개로 상당한 딜량을 낼 수 있는 킷을 가지고 있다. 이런 힐러의
  딜량이 같은 판 아군 탱커/딜러의 딜량에 준할 정도로 높으면서 힐량도
  충분히 뒷받침된다면(치유량이 부족하지 않다면), 그건 힐러로서 이례적
  으로 뛰어난 기여다 — "힐러니까 힐량/도움만 본다"는 식으로 이 딜량을
  순위·비교 판단에서 빼거나 무시하지 마라. 역할이 다른 아군(예: 탱커)과
  비교할 때도 이 힐러의 딜량을 그 아군의 딜량과 나란히 놓고 판단 근거로
  반드시 포함해라 — 킬/도움/데스/힐량만 보고 판단하면 안 된다."""


def stat_judgement_rules(*, include_peer_comparison: bool = True) -> str:
    """스탯창 피드백/채팅 답변이 공통으로 쓰는 판단 규칙 묶음."""
    rules = [HERO_KIT_AWARENESS_RULE]
    if include_peer_comparison:
        rules.append(PEER_COMPARISON_RULE)
    rules.extend([MITIGATION_KIT_RULE, RESOURCE_HEALER_RULE, HERO_TRAIT_PHRASING_RULE])
    return "\n".join(rules)


